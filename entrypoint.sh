#!/bin/sh
echo "🚀 Запуск миграций базы данных..."

# Запускаем скрипт миграций. Если он вернет ошибку (код != 0), останавливаемся.
python migrate.py

if [ \$? -ne 0 ]; then
  echo "❌ Миграции не прошли. Контейнер останавливается."
  exit 1
fi

echo "✅ Миграции успешны. Запуск бота..."
exec python main.py
